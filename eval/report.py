#!/usr/bin/env python3
"""
Render the Phase 0.5 raw results into a markdown data appendix.

Kept separate from the decision write-up on purpose. `model-selection.md` argues a case and
is written by hand; this file is only tables, regenerated whenever a benchmark is re-run, so
the numbers in the argument can always be checked against a current source.

Usage:
    python3 eval/report.py > eval/results-data.md
"""

import collections
import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
from situations import SITUATIONS  # noqa: E402


def load(name):
    p = HERE / name
    return json.loads(p.read_text()) if p.exists() else None


def classify(msg):
    if "required property" in msg:
        return "missing required field"
    if "not one of" in msg:
        return "bad enum value"
    if "greater than the maximum" in msg or "less than the minimum" in msg:
        return "out of range"
    if "not of type" in msg:
        return "wrong type"
    if "Additional properties" in msg:
        return "invented field"
    return msg[:40]


def emit_a1(tools):
    print("## A1 — tool-call emission and argument validity\n")
    print(f"20 situations, {tools[list(tools)[0]]['summary']['n'] // 20} samples each, "
          "temperature 0.4.\n")

    cols = ["emission_rate", "native_emission_rate", "validity_rate", "validity_rate_strict",
            "end_to_end_rate", "plausible_choice_rate", "valid_after_repair_rate"]
    labels = ["emission", "native emission", "valid args", "valid args (no coercion)",
              "end-to-end", "plausible tool choice", "valid after 1 repair"]

    print("| metric | " + " | ".join(tools) + " |")
    print("|---" * (len(tools) + 1) + "|")
    for col, label in zip(cols, labels):
        cells = []
        for m in tools:
            v = tools[m]["summary"].get(col)
            cells.append("—" if v is None else f"{v:.0%}")
        print(f"| {label} | " + " | ".join(cells) + " |")
    lat = [f"{tools[m]['summary']['median_latency']:.1f}s" for m in tools]
    print("| median latency / call | " + " | ".join(lat) + " |")
    print()

    print("### Where the invalid arguments came from\n")
    for m, data in tools.items():
        bad = [r for r in data["rows"] if r["outcome"] == "invalid_args"]
        by_tool = collections.Counter(r["tool"] for r in bad)
        kinds = collections.Counter(classify(e.split(":", 1)[1].strip())
                                    for r in bad for e in r.get("errors", []))
        rescued = sum(1 for r in data["rows"]
                      if r["outcome"] == "valid" and not r.get("valid_without_coercion"))
        print(f"**{m}** — {len(bad)} invalid of {data['summary']['n']}")
        print(f"- by tool: {dict(by_tool) or 'none'}")
        print(f"- by error kind: {dict(kinds) or 'none'}")
        print(f"- rescued by type coercion: {rescued}\n")


def emit_choices(tools):
    print("## Tool choice per situation\n")
    print("`expected` lists the tools a reasonable interviewer might pick. It is a soft "
          "signal, not the pass criterion — but a model that misses most of them is not "
          "conducting an interview.\n")
    exp = {s["id"]: s["expected"] for s in SITUATIONS}
    notes = {s["id"]: s["note"] for s in SITUATIONS}

    print("| situation | expected | " + " | ".join(tools) + " |")
    print("|---" * (len(tools) + 2) + "|")
    for sid in exp:
        cells = []
        for m in tools:
            picks = collections.Counter(r["tool"] for r in tools[m]["rows"]
                                        if r["id"] == sid and r["tool"])
            got = ", ".join(f"{k}×{v}" for k, v in picks.most_common(2)) or "—"
            hit = any(t in exp[sid] for t in picks)
            cells.append(("✅ " if hit else "❌ ") + got)
        print(f"| `{sid}`<br><sub>{notes[sid]}</sub> | {' / '.join(exp[sid])} | "
              + " | ".join(cells) + " |")
    print()


def emit_a2(lat):
    print("## A2 — prompt-eval throughput and first-token latency\n")
    hw = lat["hardware"]
    print(f"Hardware: **{hw['cpu']}, {hw['ram_gb']} GB**, {hw['platform']}\n")
    print("| model | prompt tokens | prompt eval | prompt tok/s | first token | gen tok/s |")
    print("|---|---|---|---|---|---|")
    for model, sizes in lat["models"].items():
        for _, p in sorted(sizes.items(), key=lambda kv: int(kv[0])):
            print(f"| {model} | {p['prompt_tokens']} | {p['prompt_eval_s']:.2f}s | "
                  f"{p['prompt_tokens_per_s']:.0f} | {p['first_token_s']:.2f}s | "
                  f"{p['gen_tokens_per_s']:.1f} |")
    print()


def main():
    print("# Phase 0.5 — raw results\n")
    print("Generated by `python3 eval/report.py`. Do not edit by hand; re-run the "
          "benchmarks and regenerate.\n")
    tools = load("bench_tools_raw.json")
    if tools:
        emit_a1(tools)
        emit_choices(tools)
    lat = load("bench_latency_raw.json")
    if lat:
        emit_a2(lat)


if __name__ == "__main__":
    main()
